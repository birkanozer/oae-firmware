const char *uiText(TextId id, Lang lang)
{
    const size_t i = static_cast<size_t>(id);
    if (i >= static_cast<size_t>(TextId::Count))
        return "";
    return lang == Lang::TR ? kTable[i].tr : kTable[i].en;
}

